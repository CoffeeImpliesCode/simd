const std = @import("std");
const simd = @import("simd.zig");

/// JSON-family lexical modes supported by the allocation-free scanner.
pub const Mode = enum {
    json,
    jsonl,
    jsonc,
    json5,
};

pub const CommentState = enum {
    none,
    line,
    block,
};

/// The bounded lexical state carried between scanner feeds.
///
/// The state contains no input bytes and owns no allocation. Prefix buffers are
/// limited to one UTF-8 sequence or one comment terminator.
pub const State = struct {
    in_string: bool = false,
    in_atom: bool = false,
    quote_delimiter: u8 = 0,
    comment: CommentState = .none,
    ends_in_backslash: bool = false,
    backslash_run_odd: bool = false,
    pending_slash: bool = false,
    pending_escape: bool = false,
    pending_escape_offset: usize = 0,
    pending_unicode_len: u2 = 0,
    pending_unicode: [3]u8 = .{ 0, 0, 0 },
    pending_unicode_offset: usize = 0,
    block_comment_ends_in_star: bool = false,
    pending_line_comment_unicode_len: u2 = 0,
    pending_line_comment_unicode: [2]u8 = .{ 0, 0 },
    next_offset: usize = 0,
};

/// Errors generated by the scanner or by its checked output sink.
///
/// The scanner itself does not allocate. `CapacityExceeded` is propagated from
/// a sink that cannot accept all offsets, while `InputTooLarge` protects u32
/// structural offsets.
pub const Error = error{
    CapacityExceeded,
    InputTooLarge,
    NonContiguousInput,
};

const max_offset: usize = std.math.maxInt(u32);

/// Feeds one contiguous input slice into the mode-specialized scanner.
///
/// `base_offset` is absolute in the complete source. The first call must use
/// zero and later calls must start at the prior end offset. The sink receives
/// either a checked mask with absolute base or one checked absolute offset.
pub fn feed(
    comptime VLEN: usize,
    comptime mode: Mode,
    state: *State,
    input: []const u8,
    base_offset: usize,
    sink: anytype,
) Error!void {
    comptime std.debug.assert(VLEN >= 4);

    if (base_offset != state.next_offset) return error.NonContiguousInput;
    if (base_offset > max_offset) return error.InputTooLarge;
    if (input.len > max_offset - base_offset) return error.InputTooLarge;

    var local_offset: usize = 0;
    while (local_offset < input.len) {
        const valid_count = @min(VLEN, input.len - local_offset);
        var bytes: [VLEN]u8 = @splat(0);
        @memcpy(bytes[0..valid_count], input[local_offset..][0..valid_count]);
        const absolute_offset = base_offset + local_offset;

        switch (mode) {
            .json, .jsonl => try processStrictBlock(
                VLEN,
                mode,
                state,
                bytes,
                valid_count,
                absolute_offset,
                sink,
            ),
            .jsonc, .json5 => try processDialectBlock(
                VLEN,
                mode,
                state,
                bytes,
                valid_count,
                absolute_offset,
                sink,
            ),
        }
        local_offset += valid_count;
    }

    state.next_offset = base_offset + input.len;
}

/// Flushes bounded lexical prefixes at end of input.
pub fn finish(comptime mode: Mode, state: *State, sink: anytype) Error!void {
    if (state.pending_slash) {
        state.pending_slash = false;
        state.in_atom = switch (mode) {
            .json, .jsonc => true,
            .jsonl, .json5 => false,
        };
    }

    if (state.pending_escape) {
        state.pending_escape = false;
        state.in_atom = false;
    }

    if (state.pending_unicode_len != 0) {
        if (!state.in_atom) {
            try sink.appendOffset(state.pending_unicode_offset);
        }
        state.pending_unicode_len = 0;
        state.in_atom = true;
    }

    // A split U+2028/U+2029 prefix is not a token by itself. An incomplete
    // line-comment terminator remains inside the comment at EOF.
    state.pending_line_comment_unicode_len = 0;
}

fn processStrictBlock(
    comptime VLEN: usize,
    comptime mode: Mode,
    state: *State,
    bytes: [VLEN]u8,
    valid_count: usize,
    base_offset: usize,
    sink: anytype,
) Error!void {
    const Mask = simd.Mask(VLEN);
    const Shift = std.math.Log2Int(Mask);
    const chunk: simd.Vec(VLEN, u8) = bytes;
    const valid = simd.validMask(VLEN, valid_count);

    const backslashes = simd.matchByte(VLEN, chunk, '\\') & valid;
    var odd_backslash_ends = simd.computeBackslashRuns(
        Mask,
        backslashes,
        state.ends_in_backslash,
    ).odd_length_ends & valid;
    if (state.ends_in_backslash) {
        if ((backslashes & @as(Mask, 1)) == 0) {
            if (state.backslash_run_odd) {
                odd_backslash_ends |= 1;
            } else {
                odd_backslash_ends &= ~@as(Mask, 1);
            }
        } else if (state.backslash_run_odd) {
            odd_backslash_ends ^= leadingRunEndMask(VLEN, backslashes, valid_count);
        }
    }

    const quotes = simd.matchByte(VLEN, chunk, '"') & valid;
    const unescaped_quotes = quotes & ~odd_backslash_ends;
    const inside_without_closing = simd.prefixXor(Mask, unescaped_quotes) ^
        if (state.in_string) ~@as(Mask, 0) else 0;
    const opening_quotes = unescaped_quotes & inside_without_closing;
    const string_mask = inside_without_closing | unescaped_quotes;
    const outside_string = ~string_mask & valid;

    const structural = (simd.matchAny4(VLEN, chunk, '{', '}', '[', ']') |
        simd.matchAny2(VLEN, chunk, ':', ',')) & valid;
    const whitespace = simd.matchJsonWhitespace(VLEN, chunk) & valid;
    const atom_candidates = (simd.matchRange(VLEN, chunk, '0', '9') |
        simd.matchAny4(VLEN, chunk, '-', 't', 'f', 'n')) & valid;
    const atom_active = outside_string & ~(structural | whitespace | quotes);
    const atom_starts = atom_candidates & atom_active &
        ~((atom_active << @as(Shift, 1)) |
            if (state.in_atom) @as(Mask, 1) else 0);
    const record_boundaries: Mask = if (mode == .jsonl)
        simd.matchByte(VLEN, chunk, '\n') & valid
    else
        0;
    const indexes = ((structural | atom_starts | record_boundaries) & outside_string) |
        opening_quotes;

    try sink.appendMask(Mask, indexes, base_offset);

    const last_bit: Mask = @as(Mask, 1) <<
        @as(Shift, @intCast(valid_count - 1));
    state.in_string = (inside_without_closing & last_bit) != 0;
    state.quote_delimiter = if (state.in_string) '"' else 0;
    state.ends_in_backslash = bytes[valid_count - 1] == '\\';
    state.backslash_run_odd = simd.trailingRunOdd(
        VLEN,
        backslashes,
        valid_count,
        state.backslash_run_odd,
    );
    state.in_atom = (atom_active & last_bit) != 0;
}

fn processDialectBlock(
    comptime VLEN: usize,
    comptime mode: Mode,
    state: *State,
    bytes: [VLEN]u8,
    valid_count: usize,
    base_offset: usize,
    sink: anytype,
) Error!void {
    const Mask = simd.Mask(VLEN);
    const Shift = std.math.Log2Int(Mask);
    const chunk: simd.Vec(VLEN, u8) = bytes;
    const valid = simd.validMask(VLEN, valid_count);
    const backslashes = simd.matchByte(VLEN, chunk, '\\') & valid;
    var odd_backslash_ends = simd.computeBackslashRuns(
        Mask,
        backslashes,
        state.ends_in_backslash,
    ).odd_length_ends & valid;
    if (state.ends_in_backslash) {
        if ((backslashes & @as(Mask, 1)) == 0) {
            if (state.backslash_run_odd) {
                odd_backslash_ends |= 1;
            } else {
                odd_backslash_ends &= ~@as(Mask, 1);
            }
        } else if (state.backslash_run_odd) {
            odd_backslash_ends ^= leadingRunEndMask(VLEN, backslashes, valid_count);
        }
    }

    const unescaped_double_quotes =
        simd.matchByte(VLEN, chunk, '"') & valid & ~odd_backslash_ends;
    const unescaped_single_quotes = if (mode == .json5)
        simd.matchByte(VLEN, chunk, '\'') & valid & ~odd_backslash_ends
    else
        0;
    const structural = (simd.matchAny4(VLEN, chunk, '{', '}', '[', ']') |
        simd.matchAny2(VLEN, chunk, ':', ',')) & valid;
    const slash = simd.matchByte(VLEN, chunk, '/') & valid;
    const star = simd.matchByte(VLEN, chunk, '*') & valid;
    const line_end = simd.matchAny2(VLEN, chunk, '\n', '\r') & valid;
    const atom_mask = switch (mode) {
        .jsonc => (simd.matchRange(VLEN, chunk, '0', '9') |
            simd.matchAny4(VLEN, chunk, '-', 't', 'f', 'n')) & valid,
        .json5 => json5AtomMask(VLEN, chunk, valid),
        else => unreachable,
    };

    // Atom starts are independent of quote/comment state. False candidates
    // inside those regions are discarded by processDialectByte, while this
    // keeps opposite quote delimiters from hiding a real atom start.
    const atom_starts = atom_mask &
        ~((atom_mask << @as(Shift, 1)) |
            if (state.in_atom) @as(Mask, 1) else 0);
    var candidates = structural | slash | star |
        unescaped_double_quotes | unescaped_single_quotes | atom_starts;
    if (mode == .json5) {
        candidates |= simd.matchRange(VLEN, chunk, 0x80, 0xff) & valid;
        candidates |= simd.matchByte(VLEN, chunk, '\\') & valid;
        candidates |= line_end;
    } else {
        candidates |= line_end;
    }


    var visible: Mask = 0;
    var cursor: usize = 0;
    while (cursor < valid_count) {
        const force = state.pending_unicode_len != 0 or
            state.pending_line_comment_unicode_len != 0 or
            state.pending_slash or state.pending_escape or
            state.block_comment_ends_in_star;
        const candidate_offset = if (force)
            cursor
        else
            nextSetBit(Mask, candidates, cursor, valid_count) orelse {
                updateOrdinarySpan(mode, state, &bytes, cursor, valid_count);
                break;
            };

        if (candidate_offset > cursor) {
            updateOrdinarySpan(mode, state, &bytes, cursor, candidate_offset);
        }

        const consumed = try processDialectByte(
            VLEN,
            mode,
            state,
            &bytes,
            candidate_offset,
            base_offset,
            unescaped_double_quotes,
            unescaped_single_quotes,
            &visible,
            sink,
        );
        if (!consumed) {
            _ = try processDialectByte(
                VLEN,
                mode,
                state,
                &bytes,
                candidate_offset,
                base_offset,
                unescaped_double_quotes,
                unescaped_single_quotes,
                &visible,
                sink,
            );
        }
        cursor = candidate_offset + 1;
    }

    try sink.appendMask(Mask, visible, base_offset);
    state.ends_in_backslash = bytes[valid_count - 1] == '\\';
    state.backslash_run_odd = simd.trailingRunOdd(
        VLEN,
        backslashes,
        valid_count,
        state.backslash_run_odd,
    );
}

fn processDialectByte(
    comptime VLEN: usize,
    comptime mode: Mode,
    state: *State,
    bytes: []const u8,
    local_offset: usize,
    base_offset: usize,
    unescaped_double_quotes: simd.Mask(VLEN),
    unescaped_single_quotes: simd.Mask(VLEN),
    visible: *simd.Mask(VLEN),
    sink: anytype,
) Error!bool {
    const byte = bytes[local_offset];

    if (state.pending_line_comment_unicode_len != 0) {
        const consumed = appendPendingLineCommentUnicode(state, byte);
        if (consumed) return true;
    }
    if (state.pending_unicode_len != 0) {
        const consumed = try appendPendingUnicode(
            VLEN,
            mode,
            state,
            byte,
            visible,
            base_offset,
            sink,
        );
        if (consumed) return true;
    }

    switch (state.comment) {
        .line => {
            if (byte == '\n' or byte == '\r') {
                state.comment = .none;
                state.in_atom = false;
                return true;
            }
            if (mode == .json5 and byte == 0xe2) {
                state.pending_line_comment_unicode[0] = byte;
                state.pending_line_comment_unicode_len = 1;
            }
            return true;
        },
        .block => {
            if (state.block_comment_ends_in_star) {
                state.block_comment_ends_in_star = false;
                if (byte == '/') {
                    state.comment = .none;
                    state.in_atom = false;
                    return true;
                }
            }
            if (byte == '*') state.block_comment_ends_in_star = true;
            return true;
        },
        .none => {},
    }

    if (state.in_string) {
        const bit = @as(simd.Mask(VLEN), 1) <<
            @as(std.math.Log2Int(simd.Mask(VLEN)), @intCast(local_offset));
        const quote_mask = if (state.quote_delimiter == '\'')
            unescaped_single_quotes
        else
            unescaped_double_quotes;
        if ((quote_mask & bit) != 0) {
            state.in_string = false;
            state.quote_delimiter = 0;
            state.in_atom = false;
        }
        return true;
    }

    if (state.pending_slash) {
        state.pending_slash = false;
        if (commentsEnabled(mode) and (byte == '/' or byte == '*')) {
            state.comment = if (byte == '/') .line else .block;
            state.in_atom = false;
            return true;
        }
        state.in_atom = switch (mode) {
            .jsonc => true,
            .json5 => false,
            else => unreachable,
        };
        return false;
    }

    if (mode == .json5 and state.pending_escape) {
        state.pending_escape = false;
        if (byte == 'u') {
            if (!state.in_atom) {
                try recordOffset(
                    VLEN,
                    visible,
                    base_offset,
                    state.pending_escape_offset,
                    sink,
                );
            }
            state.in_atom = true;
            return true;
        }
        state.in_atom = false;
        return false;
    }

    if (mode == .json5 and byte == '\\') {
        state.pending_escape = true;
        state.pending_escape_offset = base_offset + local_offset;
        return true;
    }

    const bit = @as(simd.Mask(VLEN), 1) <<
        @as(std.math.Log2Int(simd.Mask(VLEN)), @intCast(local_offset));
    const is_quote = (unescaped_double_quotes & bit) != 0 or
        (mode == .json5 and (unescaped_single_quotes & bit) != 0);
    if (is_quote) {
        state.in_string = true;
        state.quote_delimiter = byte;
        state.in_atom = false;
        return true;
    }
    // Delay slash classification until the next byte disambiguates a comment.
    if (byte == '/') {
        state.pending_slash = true;
        return true;
    }

    if (isStructuralByte(byte)) {
        try recordOffset(VLEN, visible, base_offset, base_offset + local_offset, sink);
        state.in_atom = false;
        return true;
    }

    if (mode == .json5 and startsUnicodeWhitespace(byte)) {
        state.pending_unicode[0] = byte;
        state.pending_unicode_len = 1;
        state.pending_unicode_offset = base_offset + local_offset;
        return true;
    }

    const atom = switch (mode) {
        .jsonc => isJsoncAtomByte(byte),
        .json5 => isJson5AtomByte(byte, state.in_atom),
        else => unreachable,
    };
    if (atom) {
        if (!state.in_atom) {
            try recordOffset(VLEN, visible, base_offset, base_offset + local_offset, sink);
        }
        state.in_atom = true;
        return true;
    }

    state.in_atom = switch (mode) {
        .jsonc => !isJsonWhitespace(byte),
        .json5 => false,
        else => unreachable,
    };
    return true;
}

fn appendPendingUnicode(
    comptime VLEN: usize,
    comptime mode: Mode,
    state: *State,
    byte: u8,
    visible: *simd.Mask(VLEN),
    base_offset: usize,
    sink: anytype,
) Error!bool {
    if (mode != .json5) return false;
    const length: usize = state.pending_unicode_len;
    const first = state.pending_unicode[0];

    if (length == 1) {
        const expected = switch (first) {
            0xc2 => byte == 0xa0,
            0xe1 => byte == 0x9a,
            0xe2 => byte == 0x80 or byte == 0x81,
            0xe3 => byte == 0x80,
            0xef => byte == 0xbb,
            else => false,
        };
        const continuation = byte >= 0x80 and byte <= 0xbf;
        if (!expected and !continuation) {
            if (!state.in_atom) {
                try recordOffset(
                    VLEN,
                    visible,
                    base_offset,
                    state.pending_unicode_offset,
                    sink,
                );
            }
            state.pending_unicode_len = 0;
            state.in_atom = true;
            return false;
        }
    } else if (length == 2 and (byte < 0x80 or byte > 0xbf)) {
        if (!state.in_atom) {
            try recordOffset(
                VLEN,
                visible,
                base_offset,
                state.pending_unicode_offset,
                sink,
            );
        }
        state.pending_unicode_len = 0;
        state.in_atom = true;
        return false;
    }

    state.pending_unicode[length] = byte;
    state.pending_unicode_len += 1;
    const count: usize = state.pending_unicode_len;
    const complete = switch (first) {
        0xc2 => count >= 2,
        0xe1, 0xe2, 0xe3, 0xef => count >= 3,
        else => true,
    };
    if (!complete) return true;

    const pending_bytes = state.pending_unicode;
    const unicode_whitespace = switch (first) {
        0xc2 => pending_bytes[1] == 0xa0,
        0xe1 => pending_bytes[1] == 0x9a and pending_bytes[2] == 0x80,
        0xe2 => (pending_bytes[1] == 0x80 and
            ((pending_bytes[2] >= 0x80 and pending_bytes[2] <= 0x8a) or
                pending_bytes[2] == 0xa8 or pending_bytes[2] == 0xa9 or
                pending_bytes[2] == 0xaf)) or
            (pending_bytes[1] == 0x81 and pending_bytes[2] == 0x9f),
        0xe3 => pending_bytes[1] == 0x80 and pending_bytes[2] == 0x80,
        0xef => pending_bytes[1] == 0xbb and pending_bytes[2] == 0xbf,
        else => false,
    };
    if (unicode_whitespace) {
        state.in_atom = false;
    } else {
        if (!state.in_atom) {
            try recordOffset(
                VLEN,
                visible,
                base_offset,
                state.pending_unicode_offset,
                sink,
            );
        }
        state.in_atom = true;
    }
    state.pending_unicode_len = 0;
    return true;
}
fn appendPendingLineCommentUnicode(state: *State, byte: u8) bool {
    const length: usize = state.pending_line_comment_unicode_len;
    if (length == 1) {
        if (byte != 0x80) {
            state.pending_line_comment_unicode_len = 0;
            return false;
        }
        state.pending_line_comment_unicode[1] = byte;
        state.pending_line_comment_unicode_len = 2;
        return true;
    }

    std.debug.assert(length == 2);
    state.pending_line_comment_unicode_len = 0;
    if (byte == 0xa8 or byte == 0xa9) {
        state.comment = .none;
        state.in_atom = false;
        return true;
    }
    return false;
}

fn updateOrdinarySpan(
    comptime mode: Mode,
    state: *State,
    bytes: []const u8,
    start: usize,
    end: usize,
) void {
    if (start >= end) return;
    if (state.in_string) return;
    if (state.comment != .none) return;

    const byte = bytes[end - 1];
    state.in_atom = switch (mode) {
        .jsonc => !isJsonWhitespace(byte),
        .json5 => isJson5AsciiAtom(byte),
        else => unreachable,
    };
}


fn recordOffset(
    comptime VLEN: usize,
    visible: *simd.Mask(VLEN),
    base_offset: usize,
    offset: usize,
    sink: anytype,
) Error!void {
    if (offset >= base_offset and offset - base_offset < VLEN) {
        const Shift = std.math.Log2Int(simd.Mask(VLEN));
        visible.* |= @as(simd.Mask(VLEN), 1) <<
            @as(Shift, @intCast(offset - base_offset));
        return;
    }
    try sink.appendOffset(offset);
}

fn nextSetBit(
    comptime T: type,
    mask: T,
    start: usize,
    valid_count: usize,
) ?usize {
    if (start >= valid_count) return null;
    const Shift = std.math.Log2Int(T);
    const remaining = mask & (@as(T, std.math.maxInt(T)) << @as(Shift, @intCast(start)));
    if (remaining == 0) return null;
    const offset: usize = @intCast(@ctz(remaining));
    return if (offset < valid_count) offset else null;
}

fn shiftLeftMask(comptime T: type, mask: T, amount: usize) T {
    const bits = @typeInfo(T).int.bits;
    if (amount >= bits) return 0;
    const Shift = std.math.Log2Int(T);
    return mask << @as(Shift, @intCast(amount));
}

fn leadingRunEndMask(
    comptime VLEN: usize,
    backslashes: simd.Mask(VLEN),
    valid_count: usize,
) simd.Mask(VLEN) {
    const Mask = simd.Mask(VLEN);
    const Shift = std.math.Log2Int(Mask);
    const valid = simd.validMask(VLEN, valid_count);
    const non_backslashes = ~backslashes | ~valid;
    if (non_backslashes == 0) return 0;
    const run_length: usize = @intCast(@ctz(non_backslashes));
    if (run_length >= valid_count) return 0;
    return @as(Mask, 1) << @as(Shift, @intCast(run_length));
}

fn json5AtomMask(
    comptime VLEN: usize,
    chunk: simd.Vec(VLEN, u8),
    valid: simd.Mask(VLEN),
) simd.Mask(VLEN) {
    const prefixes = simd.matchAny4(VLEN, chunk, 0xc2, 0xe1, 0xe2, 0xe3) |
        simd.matchByte(VLEN, chunk, 0xef);
    const ascii = simd.matchRange(VLEN, chunk, '0', '9') |
        simd.matchRange(VLEN, chunk, 'a', 'z') |
        simd.matchRange(VLEN, chunk, 'A', 'Z') |
        simd.matchAny4(VLEN, chunk, '-', '+', '.', '_') |
        simd.matchByte(VLEN, chunk, '$');
    const high_leading = simd.matchRange(VLEN, chunk, 0xc0, 0xff) & ~prefixes;
    return (ascii | high_leading) & valid;
}

fn commentsEnabled(comptime mode: Mode) bool {
    return mode == .jsonc or mode == .json5;
}

fn isStructuralByte(byte: u8) bool {
    return switch (byte) {
        '{', '}', '[', ']', ':', ',' => true,
        else => false,
    };
}

fn isJsonWhitespace(byte: u8) bool {
    return switch (byte) {
        ' ', '\t', '\n', '\r' => true,
        else => false,
    };
}

fn isJsoncAtomByte(byte: u8) bool {
    return switch (byte) {
        '-', 't', 'f', 'n', '0'...'9' => true,
        else => false,
    };
}

fn isJson5AsciiAtom(byte: u8) bool {
    return switch (byte) {
        '-', '+', '.', '0'...'9', 'a'...'z', 'A'...'Z', '_', '$' => true,
        else => false,
    };
}

fn isJson5AtomByte(byte: u8, previous_atom: bool) bool {
    return switch (byte) {
        '-', '+', '.', '0'...'9', 'a'...'z', 'A'...'Z', '_', '$' => true,
        0x80...0xbf => previous_atom,
        0xc0...0xff => !startsUnicodeWhitespace(byte),
        else => false,
    };
}

fn startsUnicodeWhitespace(byte: u8) bool {
    return switch (byte) {
        0xc2, 0xe1, 0xe2, 0xe3, 0xef => true,
        else => false,
    };
}
